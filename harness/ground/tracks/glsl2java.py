#!/usr/bin/env python3
"""Generate src/pzopt/pzopt/GroundTracksGlsl.java from the .glsl files here (the rig reads the same files).
usage: glsl2java.py   (run after editing gt_*.glsl; the Java is committed, the build does not need Python)"""
import os, re
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "../../../src/pzopt/pzopt/GroundTracksGlsl.java")

def lit(text):
    lines = text.rstrip("\n").split("\n")
    out = []
    for ln in lines:
        out.append('      "' + ln.replace("\\", "\\\\").replace('"', '\\"') + '"')
    return "String.join(\"\\n\",\n" + ",\n".join(out) + ")"

def read(n):
    return open(os.path.join(HERE, n)).read()

bake = read("gt_bake.glsl")
vi, fi = bake.index("//#VERT"), bake.index("//#FRAG")
consts = {
    "RULES": read("gt_rules.glsl"),
    "LOOK": read("gt_look.glsl"),
    "CS": read("gt_cs.glsl"),
    "BAKE_VERT": bake[vi + len("//#VERT\n"):fi],
    "BAKE_FRAG": bake[fi + len("//#FRAG\n"):],
}
body = []
for k, v in consts.items():
    body.append("   static final String %s = %s;\n" % (k, lit(v)))
src = """package pzopt;

/**
 * GENERATED by harness/ground/tracks/glsl2java.py from harness/ground/tracks/gt_*.glsl (the offline rig reads the same
 * files): edit the .glsl and run the script. The ground tracks' rules (stamp, relax, decay), look, compute pass and bake pass.
 */
final class GroundTracksGlsl {
   private GroundTracksGlsl() {
   }

""" + "\n".join(body) + "}\n"
open(OUT, "w").write(src)
print("wrote", OUT, sum(len(v) for v in consts.values()), "chars")
